#!/bin/bash
#
# MediaMTX `runOnDemand` дэгээ — урсгалыг ҮЗЭГЧЭЭР удирдана.
#
# ── Яагаад ──────────────────────────────────────────────────────────────
# Барилга бүх камерыг 24 цаг дамжуулбал шугам дүүрдэг (хэмжилтээр нэг
# обьектын 34 урсгал = 18 Mbps), улмаар саатал минутаар хуримтлагдана.
# Гэтэл бодит үзэгч зэрэг 1-2 камер хардаг.
#
# ── Хэрхэн ──────────────────────────────────────────────────────────────
# MediaMTX нь НИЙТЛЭГЧГҮЙ зам дээр уншигч ирэхэд ЭНЭ скриптийг ажиллуулж,
# `runOnDemandStartTimeout` хугацаанд нийтлэгчийг хүлээнэ. Скрипт backend-д
# хэлж, backend socket-оор барилгын worker-т мэдэгдэнэ.
#
# Сүүлийн уншигч гарснаас `runOnDemandCloseAfter` хугацааны дараа MediaMTX
# скриптийг TERM-ээр таслана — тэр үед `trap` нь `stop`-ыг илгээнэ.
#
# Суулгах:
#   install -m 755 mediamtx-urgats.sh /opt/mediamtx-urgats.sh

set -u

ZAM="${1:-}"
API="http://127.0.0.1:8084/camera/urgats"

if [ -z "$ZAM" ]; then
    echo "urgats: зам дамжуулаагүй" >&2
    exit 1
fi

khel() {
    curl -s -m 8 -X POST \
        -H 'Content-Type: application/json' \
        -d "{\"path\":\"$ZAM\"}" \
        "$API/$1" >/dev/null 2>&1 || true
}

zogsooyo() {
    khel stop
    exit 0
}

# MediaMTX таслахад ЗААВАЛ stop илгээнэ — үгүй бол ffmpeg мөнхөд ажиллана.
trap zogsooyo TERM INT HUP

khel start

# MediaMTX бидний процессыг таслах хүртэл амьд байна.
#
# `start`-ыг 30 секунд тутам ДАВТАН илгээнэ. Шалтгаан: барилгын worker дахин
# асвал урсгал зогсох боловч энэ скрипт аль хэдийн `start` илгээчихсэн тул
# хэн ч дахин хэлэхгүй — үзэгч хоосон дэлгэц харна. Давталт нь өөрөө
# эдгээнэ. Worker тал нь ажиллаж байгаа урсгалыг дахин асаахгүй тул
# давтах нь ямар ч хор хөнөөлгүй (idempotent).
#
# `sleep`-ийг дэвсгэрт тавиад `wait` хийх нь чухал: bash нь урд талын
# командыг дуусахаас нааш trap-ыг ажиллуулдаггүй тул жирийн `sleep 30`
# бичвэл зогсох дохио цаг хугацаандаа хүрэхгүй.
while :; do
    for _ in 1 2 3 4 5 6; do
        sleep 5 &
        wait $!
    done
    khel start
done
